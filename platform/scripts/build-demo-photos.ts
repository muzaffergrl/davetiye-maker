#!/usr/bin/env node
// G155 (G090 P1-02): the live demo's sample photos -> platform/public/demo/<theme>/<slot key>-<W>w.webp + lib/claim/demo-photos.json.
//
// /start/demo/<theme> (lib/claim/demo-page.ts) fills the design's empty photo slots with them (lib/claim/demo-photos.ts),
// so the demo the listing links to ("sample names and photos") shows the design's own fictional couple, not empty
// "your photo here" frames. Sources: each theme's PAKET 2 photos, collections/<NN>/assets/gpt/photos/<slot key>.(jpg|png|…)
// (theme → collection: tools/katalog.py, as theme-check). A theme without its own PAKET 2 photos gets none (never another
// design's), and a theme whose demo record sets its photos itself (21 Crimson: theme assets) is left as it is.
//
// Each photo is centre-cropped to the slot's theme.json aspect (as a panel upload, lib/panel/photos.ts centreCrop), at most
// DEMO_PHOTO_MAX_WIDTH wide (never enlarged), WebP; plus the lib/photo-variants.ts variants narrower than it (640 px), so
// the engine writes the same srcset as for a buyer's photo. public/ is served by the CDN and traced into no server
// function (next.config.ts), so the theme folders keep their 3 MB budget.
//
//   node scripts/build-demo-photos.ts [--theme <id>]    # build (all themes, or one: the others keep their entries)
//   node scripts/build-demo-photos.ts --check           # the manifest matches the files (exit 1 if not)

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { DEMO_PHOTO_DIR, DEMO_PHOTO_MAX_WIDTH, type DemoPhotoManifest } from '../lib/claim/demo-photos.ts';
import { centreCrop } from '../lib/panel/photos.ts';
import { parseAspect } from '../lib/panel/model.ts';
import { photoCandidates, photoFileName, variantWidths } from '../lib/photo-variants.ts';
import { listThemes } from '../lib/theme/theme.ts';
import { loadThemeEnv } from './lib/theme-env.ts';

const ROOT = path.resolve(import.meta.dirname, '..');
const PUBLIC = path.join(ROOT, 'public');
const MANIFEST = path.join(ROOT, 'lib/claim/demo-photos.json');
const WEBP_QUALITY = 74;
export const NOTE =
  'Generated by scripts/build-demo-photos.ts from collections/<NN>/assets/gpt/photos (PAKET 2, fictional couples). Do not edit by hand.';

function readManifest(): DemoPhotoManifest {
  try {
    return JSON.parse(readFileSync(MANIFEST, 'utf8')) as DemoPhotoManifest;
  } catch {
    return { _note: NOTE, themes: {} };
  }
}

/** Problems of the manifest against the files on disk (empty = consistent). */
export function checkDemoPhotos(manifest: DemoPhotoManifest = readManifest()): string[] {
  const problems: string[] = [];
  const listed = new Set<string>();
  for (const [theme, slots] of Object.entries(manifest.themes)) {
    for (const [key, url] of Object.entries(slots)) {
      const candidates = photoCandidates(url);
      if (!candidates || !url.startsWith(`/${DEMO_PHOTO_DIR}/${theme}/${key}-`)) {
        problems.push(`${theme}/${key}: ${url} is not a sample photo URL (/${DEMO_PHOTO_DIR}/${theme}/${key}-<W>w.webp)`);
        continue;
      }
      for (const c of candidates) {
        const file = path.join(PUBLIC, c.url);
        listed.add(file);
        if (!existsSync(file)) problems.push(`${theme}/${key}: ${c.url} is missing`);
      }
    }
  }
  const dir = path.join(PUBLIC, DEMO_PHOTO_DIR);
  if (existsSync(dir)) {
    for (const theme of readdirSync(dir)) {
      for (const f of readdirSync(path.join(dir, theme))) {
        const file = path.join(dir, theme, f);
        if (!listed.has(file)) problems.push(`public/${DEMO_PHOTO_DIR}/${theme}/${f} is not in lib/claim/demo-photos.json`);
      }
    }
  }
  return problems;
}

async function buildTheme(id: string): Promise<{ slots: Record<string, string> | null; notes: string[]; bytes: number }> {
  const env = loadThemeEnv({ theme: id });
  const notes: string[] = [];
  const outDir = path.join(PUBLIC, DEMO_PHOTO_DIR, id);
  rmSync(outDir, { recursive: true, force: true });
  const own = env.collectionDir ? path.join(env.collectionDir, 'assets/gpt/photos') : null;
  if (!own || env.photosDir !== own || !Object.keys(env.photoFiles).length) {
    notes.push('no PAKET 2 sample photos of its own: the demo keeps its placeholders');
    return { slots: null, notes, bytes: 0 };
  }
  const slots: Record<string, string> = {};
  let bytes = 0;
  for (const [key, slot] of Object.entries(env.manifest.photos)) {
    const media = slot.source.split('.');
    const current = media.reduce<unknown>((o, k) => (o && typeof o === 'object' ? (o as Record<string, unknown>)[k] : undefined), env.demo);
    if (typeof current === 'string' && current.trim()) {
      notes.push(`${key}: the demo record sets its own photo (${current}), left as it is`);
      continue;
    }
    const file = env.photoFiles[key];
    if (!file) {
      notes.push(`${key}: no sample photo`);
      continue;
    }
    const meta = await sharp(file).rotate().metadata();
    const swap = (meta.orientation ?? 1) >= 5;
    const w0 = (swap ? meta.height : meta.width) ?? 0;
    const h0 = (swap ? meta.width : meta.height) ?? 0;
    const ratio = parseAspect(slot.aspect);
    const crop = ratio && Math.abs(w0 / h0 / ratio - 1) > 0.01 ? centreCrop(w0, h0, ratio) : { left: 0, top: 0, width: w0, height: h0 };
    const width = Math.min(DEMO_PHOTO_MAX_WIDTH, crop.width);
    mkdirSync(outDir, { recursive: true });
    for (const w of [...variantWidths(width), width]) {
      const out = path.join(outDir, photoFileName(key, w, 'webp'));
      await sharp(file).rotate().extract(crop).resize({ width: w }).toColourspace('srgb').webp({ quality: WEBP_QUALITY, effort: 6 }).toFile(out);
      bytes += statSync(out).size;
    }
    slots[key] = `/${DEMO_PHOTO_DIR}/${id}/${photoFileName(key, width, 'webp')}`;
  }
  return { slots: Object.keys(slots).length ? slots : null, notes, bytes };
}

async function main(): Promise<void> {
  if (process.argv.includes('--check')) {
    const problems = checkDemoPhotos();
    for (const p of problems) console.error(p);
    console.log(problems.length ? `${problems.length} problem(s)` : 'demo photos: manifest and files match');
    process.exit(problems.length ? 1 : 0);
  }
  const i = process.argv.indexOf('--theme');
  const only = i >= 0 ? process.argv[i + 1] : null;
  const manifest = readManifest();
  const themes = only ? [only] : (await listThemes({ includePrivate: true })).filter((m) => !m.internal).map((m) => m.id);
  if (!only) manifest.themes = {};
  let total = 0;
  for (const id of themes) {
    const { slots, notes, bytes } = await buildTheme(id);
    if (slots) manifest.themes[id] = slots;
    else delete manifest.themes[id];
    total += bytes;
    console.log(`${id}: ${slots ? `${Object.keys(slots).length} photos, ${Math.round(bytes / 1024)} KB` : 'none'}${notes.length ? ` — ${notes.join('; ')}` : ''}`);
  }
  const sorted = Object.fromEntries(Object.entries(manifest.themes).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(MANIFEST, `${JSON.stringify({ _note: NOTE, themes: sorted }, null, 2)}\n`);
  const problems = checkDemoPhotos();
  for (const p of problems) console.error(p);
  console.log(`written ${path.relative(ROOT, MANIFEST)} (${Object.keys(sorted).length} themes; this run ${(total / 1e6).toFixed(2)} MB)`);
  if (problems.length) process.exit(1);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) await main();
